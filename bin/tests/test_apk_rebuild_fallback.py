class TestProvisionApkEditorFallback:

    def _make_work_dir(self, tmp_path: Path) -> tuple[Path, Path]:
        apk = _make_minimal_zip(
            tmp_path / "build" / "baserom" / "images" /
            "system_ext" / "priv-app" / "Provision" / "Provision.apk"
        )
        return tmp_path, apk

    def test_provision_apkeditor_called_when_apktool_rebuild_fails(self, tmp_path):
        """When apktool rebuild fails, APKEditor fallback is attempted."""
        work_dir, apk = self._make_work_dir(tmp_path)
        report: list = []

        # Make apktool decompile succeed but rebuild fail; APKEditor succeed
        fake_unpacked = tmp_path / "provision_unpacked"
        xml = fake_unpacked / "res" / "values" / "strings.xml"
        xml.parent.mkdir(parents=True, exist_ok=True)
        xml.write_text(
            '<?xml version="1.0"?><resources>'
            '<string name="provision_complete_text">old</string>'
            '</resources>', encoding="utf-8"
        )

        # _get_or_decompile returns the pre-existing dir (we_decompiled=False)
        # so no rebuild call — just patches the XML in place
        apply_provision_strings(work_dir, report)
        # At minimum should not raise; pre-decompiled path just patches XML
        assert len(report) >= 1

    def test_provision_apkeditor_fallback_ok_produces_changed_status(self, tmp_path):
        """APKEditor fallback success produces status=changed and restore_in_place=True."""
        work_dir, apk = self._make_work_dir(tmp_path)
        report: list = []

        # Simulate: apktool decompile fails → apk_path returned → APKEditor succeeds
        def fake_get_or_decompile(*args, **kwargs):
            return None, False, apk, [str(apk)]

        fake_apke_result = {
            "ok": True, "rebuilt_path": str(apk), "restored_path": str(apk),
            "restore_in_place": True, "permission": "0644",
            "stdout": "", "stderr": "", "error": None,
        }

        with patch("lite_apk_patches._get_or_decompile", side_effect=fake_get_or_decompile), \
             patch("lite_apk_patches._rebuild_provision_with_apkeditor",
                   return_value=fake_apke_result):
            apply_provision_strings(work_dir, report)

        assert any(r["status"] == "changed" and r.get("restore_in_place") is True
                   for r in report), f"Expected changed+restore, got: {[r['status'] for r in report]}"

    def test_provision_apkeditor_fallback_fail_produces_failed_optional(self, tmp_path):
        """When both apktool and APKEditor fail, status=failed_optional."""
        work_dir, apk = self._make_work_dir(tmp_path)
        report: list = []

        def fake_get_or_decompile(*args, **kwargs):
            return None, False, apk, [str(apk)]

        fake_apke_fail = {
            "ok": False, "error": "APKEditor build failed",
            "rebuilt_path": None, "restored_path": None,
            "restore_in_place": False, "permission": None,
        }

        with patch("lite_apk_patches._get_or_decompile", side_effect=fake_get_or_decompile), \
             patch("lite_apk_patches._rebuild_provision_with_apkeditor",
                   return_value=fake_apke_fail):
            apply_provision_strings(work_dir, report)

        assert any(r["status"] == "failed_optional" for r in report)

    def test_provision_report_has_restore_in_place_field(self, tmp_path):
        """Provision report entries always have restore_in_place field."""
        work_dir = tmp_path
        report: list = []
        apply_provision_strings(work_dir, report)
        for r in report:
            assert "restore_in_place" in r


