# ── helpers ────────────────────────────────────────────────────────────────────

def _mk(path: Path, content: bytes | str = "x") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")
    return path


def _make_minimal_zip(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(str(path), "w") as zf:
        zf.writestr("classes.dex", b"\x64\x65\x78\x0a", compress_type=zipfile.ZIP_STORED)
        zf.writestr("AndroidManifest.xml", b"<manifest/>")
        zf.writestr("res/values/strings.xml",
                    '<?xml version="1.0"?><resources>'
                    '<string name="provision_complete_text">old</string>'
                    '</resources>')
    return path


