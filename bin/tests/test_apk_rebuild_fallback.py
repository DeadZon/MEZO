# ══════════════════════════════════════════════════════════════════════════════

class TestOptionalFailureExitCode:

    def test_main_exits_zero_on_only_optional_failures(self, tmp_path):
        """main() exits 0 when all failures are failed_optional."""
        # The total dict with only failed_optional — non_optional_failures == 0
        totals = {
            "total_scanned": 3, "total_modified": 0,
            "total_skipped": 1, "total_skipped_not_found": 1,
            "total_failed": 2, "total_failed_optional": 2,
        }
        non_optional = totals["total_failed"] - totals.get("total_failed_optional", 0)
        assert non_optional == 0, "All 2 failures are optional — should not trigger exit 2"

    def test_main_exits_nonzero_on_fatal_failures(self):
        """main() exits 2 when there are non-optional (fatal) failures."""
        totals = {
            "total_failed": 3, "total_failed_optional": 1,
        }
        non_optional = totals["total_failed"] - totals.get("total_failed_optional", 0)
        assert non_optional == 2

    def test_apply_lite_apk_patches_returns_failed_optional_not_failed(self, tmp_path):
        """When optional rebuilds fail, the report shows failed_optional, not failed."""
        work_dir = tmp_path  # No APKs present — all will be skipped/not_found

        report = apply_lite_apk_patches(work_dir)
        all_statuses = []
        for patch_data in report["patches"].values():
            for e in patch_data["results"]:
                all_statuses.append(e["status"])

        # Must not have plain "failed" — only skipped/skipped_not_found/failed_optional
        plain_failed = [s for s in all_statuses if s == "failed"]
        assert plain_failed == [], \
            f"Got plain 'failed' entries: {plain_failed}; all statuses: {all_statuses}"

    def test_lite_apk_patches_does_not_exit_on_optional_failures(self, tmp_path):
        """apply_lite_apk_patches returns normally even with all-optional failures."""
        report = apply_lite_apk_patches(tmp_path)
        # Should return a dict, not raise or sys.exit
        assert isinstance(report, dict)
        assert "totals" in report

    def test_style_mod_runner_marks_optional_lite_apk_failed_but_continues(self, tmp_path):
        """style_mod_runner continues when lite_apk_patches exits 2 and mod is optional."""
        import style_mod_runner as smr

        # Create a fake manifest with an optional mod that exits 2
        style_dir = tmp_path / "bin" / "styles" / "Lite"
        style_dir.mkdir(parents=True, exist_ok=True)
        scripts_dir = tmp_path / "bin" / "scripts"
        scripts_dir.mkdir(parents=True, exist_ok=True)

        failing_mod = scripts_dir / "_fail_optional_mod.py"
        failing_mod.write_text("import sys; sys.exit(2)\n", encoding="utf-8")

        noop_mod = scripts_dir / "_noop_after_fail.py"
        noop_mod.write_text("import sys; sys.exit(0)\n", encoding="utf-8")

        manifest = style_dir / "mods.json"
        manifest.write_text(json.dumps({
            "style": "lite",
            "name": "Lite Test",
            "mods": [
                {"id": "fail_opt", "name": "Fail Optional",
                 "enabled": True, "required": False,
                 "python_entry": "bin/scripts/_fail_optional_mod.py"},
                {"id": "noop_after", "name": "Noop After",
                 "enabled": True, "required": False,
                 "python_entry": "bin/scripts/_noop_after_fail.py"},
            ],
        }), encoding="utf-8")

        results = smr.run_style("lite", tmp_path)

        statuses = [r["status"] for r in results]
        # Both mods should be in results (runner did not abort early)
        assert len(results) == 2, f"Expected 2 results, got: {statuses}"
        # Optional failure does not abort run
        assert statuses[0] == "failed"
        assert statuses[1] == "success"
