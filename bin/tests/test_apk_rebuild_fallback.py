class TestMiuiServicesFinderRecursive:

    def _make_jar_at(self, tmp_path: Path, rel: str) -> Path:
        jar = tmp_path / rel
        jar.parent.mkdir(parents=True, exist_ok=True)
        jar.write_bytes(b"PK")
        return jar

    def test_find_miui_services_in_known_path(self, tmp_path):
        """find_file_in_rom locates miui-services.jar in system_ext/framework."""
        self._make_jar_at(tmp_path / "build" / "baserom" / "images",
                          "system_ext/framework/miui-services.jar")
        result = _rph.find_file_in_rom(
            tmp_path,
            ["system_ext/framework/miui-services.jar",
             "system_ext/system_ext/framework/miui-services.jar"],
        )
        assert result["found"]
        assert "miui-services.jar" in result["found_path"]

    def test_find_miui_services_rglob_fallback_in_framework_patches(self, tmp_path):
        """_decompile_framework_jars finds miui-services.jar via rglob when static paths fail."""
        from deadzone_framework_patches import _decompile_framework_jars

        # Place jar in a non-standard location under build/baserom/images
        jar = self._make_jar_at(
            tmp_path,
            "build/baserom/images/system_ext/fw_custom/miui-services.jar"
        )

        outcomes = _decompile_framework_jars(tmp_path)

        mi = outcomes.get("miui_services_unpacked", {})
        # Either found (and decompile attempted) or not found (apktool unavailable)
        # The key: the jar_path should be populated (not None) from rglob
        if mi.get("decompiled") is False and mi.get("jar_path"):
            # Found via rglob but decompile failed (no apktool in test env) — expected
            assert "miui-services.jar" in mi["jar_path"]
        elif mi.get("decompiled"):
            assert "miui-services.jar" in mi["jar_path"]
        else:
            # Either not found (if rglob missed it) or jar_path is None (not found at all)
            # At minimum the searched_paths should include the rglob marker
            sp = mi.get("searched_paths", [])
            rglob_noted = any("rglob" in str(s).lower() for s in sp)
            assert rglob_noted or mi.get("jar_path") is None, \
                f"Expected rglob in searched_paths or jar_path=None: {mi}"

    def test_miui_services_candidates_include_system_ext(self):
        """_MIUI_SERVICES_JAR_CANDS includes system_ext paths."""
        from deadzone_framework_patches import _MIUI_SERVICES_JAR_CANDS
        paths_str = " ".join(_MIUI_SERVICES_JAR_CANDS)
        assert "system_ext/framework/miui-services.jar" in _MIUI_SERVICES_JAR_CANDS
        assert any("fremawork" in p for p in _MIUI_SERVICES_JAR_CANDS), \
            "typo fallback 'fremawork' should be included"

    def test_rph_miui_services_candidates_include_system_ext(self):
        """rom_patch_helpers._MIUI_SERVICES_JAR_CANDIDATES includes system_ext paths."""
        from rom_patch_helpers import _MIUI_SERVICES_JAR_CANDIDATES
        assert "system_ext/framework/miui-services.jar" in _MIUI_SERVICES_JAR_CANDIDATES
        assert any("fremawork" in p for p in _MIUI_SERVICES_JAR_CANDIDATES)


